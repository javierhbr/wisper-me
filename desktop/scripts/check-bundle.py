#!/usr/bin/env python3
"""Start bundled worker without models; verify sealed resources remain unchanged."""
import json
import os
from pathlib import Path
import signal
import subprocess
import sys

app = Path(sys.argv[1]).resolve()
runtime = app / "Contents/Resources/runtime"
worker = runtime / "worker.py"
environment = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
child = subprocess.Popen([sys.executable, "-B", str(worker)], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                         stderr=subprocess.PIPE, text=True, env=environment, start_new_session=True)
try:
    output, error = child.communicate(json.dumps({"id":"smoke","op":"ping"})+"\n"+json.dumps({"op":"quit"})+"\n", timeout=5)
    if child.returncode != 0:
        raise SystemExit("Bundled worker startup failed")
    replies = [json.loads(line) for line in output.splitlines()]
    if not any(value.get("id") == "smoke" and value.get("ok") for value in replies):
        raise SystemExit("Bundled worker protocol check failed")
finally:
    if child.poll() is None:
        os.killpg(child.pid, signal.SIGTERM)
        child.wait(timeout=5)
if list(runtime.rglob("*.pyc")):
    raise SystemExit("Generated bytecode found in the signed bundle")
subprocess.run(["/usr/bin/codesign","--verify","--deep","--strict",str(app)],check=True)
print("Bundled worker startup and sealed-resource signature check passed.")
